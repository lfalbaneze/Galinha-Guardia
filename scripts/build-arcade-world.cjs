// Export measured transparent scenery bounds without changing the artist's PNG.
const fs=require('node:fs'),path=require('node:path'),{createCanvas,loadImage}=require('@napi-rs/canvas');
const root=path.resolve(__dirname,'..'),file=path.join(root,'assets/farm/farm-arcade-93.png');
(async()=>{
  const image=await loadImage(file),c=createCanvas(image.width,image.height).getContext('2d');c.drawImage(image,0,0);
  const pixels=c.getImageData(0,0,image.width,image.height).data;
  function bands(horizontal,start,end){
    const length=horizontal?image.width:image.height,counts=new Uint32Array(length),spans=[];
    for(let a=0;a<length;a++)for(let b=start;b<end;b++){const x=horizontal?a:b,y=horizontal?b:a;if(pixels[(y*image.width+x)*4+3]>=160)counts[a]++;}
    for(let i=0;i<length;i++)if(counts[i]>=3){const prev=spans.at(-1);if(prev&&i-prev[1]<=2)prev[1]=i+1;else spans.push([i,i+1]);}
    return spans.filter(([a,b])=>b-a>24);
  }
  const rows=bands(false,0,image.width),frames={},names=[['tree','bush','pear','willow'],['bramble','shelter','barn','coop'],['silo','hay','trough','fence'],['daisies','lavender','harvest','nursery']];
  if(rows.length!==4)throw Error('World atlas rows: '+rows.length);
  for(let row=0;row<4;row++){
    const [top,bottom]=rows[row],columns=bands(true,top,bottom);
    if(columns.length!==4)throw Error('World atlas columns: '+row+'/'+columns.length);
    for(let col=0;col<4;col++){
      const [start,end]=columns[col];let l=end,r=start,t=bottom,b=top;
      for(let y=top;y<bottom;y++)for(let x=start;x<end;x++)if(pixels[(y*image.width+x)*4+3]>=160){l=Math.min(l,x);r=Math.max(r,x+1);t=Math.min(t,y);b=Math.max(b,y+1);}
      if(l<2||r>image.width-2||t<2||b>image.height-2)throw Error('Clipped scenery '+names[row][col]);
      frames[names[row][col]]=[l,t,r-l,b-t];
    }
  }
  const data={width:image.width,height:image.height,frames,image:'data:image/png;base64,'+fs.readFileSync(file).toString('base64')};
  fs.writeFileSync(path.join(root,'assets/farm/arcade-data.js'),'/* Generated by scripts/build-arcade-world.cjs. */\nconst FarmArcadeData = '+JSON.stringify(data)+';\n');
  console.log('Validated 16 scenery sprites.');
})().catch(e=>{console.error(e);process.exitCode=1;});
